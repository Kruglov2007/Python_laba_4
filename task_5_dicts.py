def combine_dicts(d1, d2)->dict:
    """
        Принимает два словаря и возвращает новый словарь со всеми элементами
        обоих словарей, сохраняя порядок их следования.

        Если ключ есть в обоих словарях, в результат попадает значение из второго словаря.
        Исходные словари не изменяются.

        :param d1: Первый исходный словарь.
        :param d2: Второй исходный словарь.
        :return: Новый объединенный словарь.
        """
    dict_a = d1 if d1 is not None else {}
    dict_b = d2 if d2 is not None else {}
    result = dict_a.copy()
    result.update(dict_b)
    return result

