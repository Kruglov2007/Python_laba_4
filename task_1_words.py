# Напишите функцию count_words(sentence), которая принимает строку и возвращает
# количество слов в ней. Слова разделены пробелами;
# несколько подряд идущих пробелов считаются одним разделителем,
# для пустой строки результат — 0.
def count_words(sentence)->int:
    # Защита от передачи None или других типов данных
    if not isinstance(sentence, str):
        return 0
    return len(sentence.split())