def count_words(sentence)->int:
    """
       Принимает строку и возвращает количество слов в ней.

       Слова разделены пробелами; несколько подряд идущих пробелов
       считаются одним разделителем, для пустой строки результат — 0.

       :param sentence: Входная строка для анализа.
       :return: Количество слов (целое число).
       """

    # Защита от передачи None или других типов данных
    if not isinstance(sentence, str):
        return 0
    return len(sentence.split())